-- ============================================================================
--  ประวัติตำแหน่งบริหาร — ใครดำรงตำแหน่งอะไร ตั้งแต่เมื่อไรถึงเมื่อไร
--
--  วิธีรัน: Supabase Dashboard > SQL Editor > วางทั้งไฟล์ > Run
--  รันซ้ำได้ ไม่พัง  ต้องรันก่อนแล้ว: multi_school_step3_rls.sql,
--  staff_status_effective_date.sql (ใช้ today_th)
--
--  ทำไมต้องมี: เดิมตำแหน่งบริหารเป็นช่องเดียวใน Teachers (id_adminrole)
--    เปลี่ยน ผอ. แล้วใบลาเก่าที่พิมพ์ซ้ำขึ้นชื่อ ผอ. คนใหม่ และดูย้อนหลัง
--    ไม่ได้ว่าปีงบที่แล้วใครเป็นอะไร
--
--  หลัก:
--    start_date = วันแรกที่ดำรงตำแหน่ง (ว่าง = ก่อนเริ่มบันทึกประวัติ)
--    end_date   = วันแรกที่ "ไม่ได้" ดำรงตำแหน่งแล้ว (ว่าง = ยังดำรงอยู่)
--                 ความหมายเดียวกับ left_date ของสถานะบุคลากร
--    ตั้ง ผอ. คนใหม่ มีผล 26 ต.ค. → ผอ. คนเดิม end_date = 26 ต.ค.
--      วันที่ 25 ยังเป็นคนเดิม · วันที่ 26 เป็นคนใหม่
--
--    แก้ได้ผ่านฟังก์ชันเท่านั้น (ไม่มี policy เขียนตรง) — การปิดตำแหน่งคนเดิม
--    กับเปิดตำแหน่งคนใหม่ต้องเกิดพร้อมกัน ถ้าแอปเขียนเองทีละแถวแล้วเน็ตหลุด
--    กลางทาง จะเหลือสองคนในตำแหน่งเดียว หรือไม่มีใครเลย
--
--    Teachers.id_adminrole ยังอยู่ = ตำแหน่ง "วันที่บันทึกล่าสุด"
--    แอปคำนวณตำแหน่งของวันใดๆ จากตารางนี้เอง ตำแหน่งที่ตั้งล่วงหน้าจึง
--    สลับตรงวันที่มีผลโดยไม่ต้องมีตัวตั้งเวลา
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1) ตาราง
-- ----------------------------------------------------------------------------

create table if not exists public."AdminPositionHistory" (
  id_history    bigint generated by default as identity primary key,
  id_school     bigint not null,
  id_user       bigint not null,
  id_adminrole  bigint not null,
  start_date    date,
  end_date      date,
  note          text,
  created_at    timestamptz not null default now(),
  created_by    bigint,
  constraint admin_position_dates
    check (end_date is null or start_date is null or end_date > start_date)
);

create index if not exists "AdminPositionHistory_school_idx"
  on public."AdminPositionHistory" (id_school);
create index if not exists "AdminPositionHistory_user_idx"
  on public."AdminPositionHistory" (id_user);

comment on table public."AdminPositionHistory" is
  'ประวัติตำแหน่งบริหาร — แก้ผ่าน assign_admin_position / delete_admin_position เท่านั้น';
comment on column public."AdminPositionHistory".start_date is
  'วันแรกที่ดำรงตำแหน่ง (ว่าง = ก่อนเริ่มบันทึกประวัติ)';
comment on column public."AdminPositionHistory".end_date is
  'วันแรกที่ไม่ได้ดำรงตำแหน่งแล้ว (ว่าง = ยังดำรงอยู่)';

alter table public."AdminPositionHistory" enable row level security;

drop policy if exists admin_position_select on public."AdminPositionHistory";
create policy admin_position_select on public."AdminPositionHistory"
  for select to authenticated
  using (public.can_see_school(id_school));


-- ----------------------------------------------------------------------------
-- 2) ตั้ง Teachers.id_adminrole ให้ตรงกับตำแหน่ง ณ วันนี้
--    ใช้ภายในฟังก์ชันข้างล่าง — ไม่มีประวัติเลย = ไม่แตะ (ข้อมูลเดิม)
-- ----------------------------------------------------------------------------

create or replace function public.sync_teacher_admin_role(p_id_user bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  today      date := public.today_th();
  today_role bigint;
begin
  if not exists (select 1 from "AdminPositionHistory" h where h.id_user = p_id_user) then
    return;
  end if;

  select h.id_adminrole into today_role
  from "AdminPositionHistory" h
  where h.id_user = p_id_user
    and (h.start_date is null or h.start_date <= today)
    and (h.end_date is null or h.end_date > today)
  order by h.start_date desc nulls last
  limit 1;

  update "Teachers" t
  set id_adminrole = today_role
  where t.id_user = p_id_user
    and t.id_adminrole is distinct from today_role;
end;
$$;

revoke all on function public.sync_teacher_admin_role(bigint) from public, anon, authenticated;


-- ----------------------------------------------------------------------------
-- 3) ตรวจสิทธิ์: ส่วนกลาง หรือแอดมินของโรงเรียนนั้น (SQL Editor ได้เสมอ)
-- ----------------------------------------------------------------------------

create or replace function public.can_manage_admin_positions(p_id_school bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() is null
      or public.is_super_admin()
      or (public.is_admin() and p_id_school = public.current_school_id());
$$;

grant execute on function public.can_manage_admin_positions(bigint) to authenticated;


-- ----------------------------------------------------------------------------
-- 4) ตั้งตำแหน่ง / เปลี่ยนตำแหน่ง / พ้นตำแหน่ง
--
--    p_id_adminrole ว่าง  = พ้นตำแหน่งบริหาร (ไม่มีตำแหน่ง) ตั้งแต่ p_start
--    p_replace = true     = คนอื่นที่ดำรงตำแหน่งเดียวกันอยู่ พ้นตำแหน่งตั้งแต่ p_start
--                           (ผอ. คนใหม่มาแทนคนเดิม) — ตำแหน่งที่มีหลายคนได้
--                           เช่น รอง ผอ. หลายฝ่าย ให้ส่ง false
--
--    ห้ามบันทึกย้อนก่อนรายการที่มีผลทีหลังอยู่แล้ว — ต้องลบรายการนั้นก่อน
--    ไม่งั้นช่วงเวลาจะซ้อนกันจนบอกไม่ได้ว่าวันไหนใครเป็นอะไร
-- ----------------------------------------------------------------------------

create or replace function public.assign_admin_position(
  p_id_user      bigint,
  p_id_adminrole bigint,
  p_start        date,
  p_replace      boolean default true,
  p_note         text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t        record;
  start_on date := coalesce(p_start, public.today_th());
  role_ok  boolean;
  replaced bigint;
begin
  select id_user, id_school, id_adminrole into t
  from "Teachers" where id_user = p_id_user;
  if not found then
    raise exception 'ไม่พบบุคลากรรหัส %', p_id_user;
  end if;

  if not public.can_manage_admin_positions(t.id_school) then
    raise exception 'ตั้งตำแหน่งบริหารได้เฉพาะผู้ดูแลระบบของโรงเรียนนี้';
  end if;

  if p_id_adminrole is not null then
    select exists (
      select 1 from adminroles a
      where a."ID_AdminRoles" = p_id_adminrole and a.id_school = t.id_school
    ) into role_ok;
    if not role_ok then
      raise exception 'ตำแหน่งบริหารนี้ไม่ใช่ของโรงเรียนเดียวกับบุคลากร';
    end if;
  end if;

  -- เริ่มประวัติจากข้อมูลเดิม: ตำแหน่งปัจจุบันที่ยังไม่มีประวัติ = ดำรงมาตั้งแต่ก่อนนี้
  -- ไม่งั้นการเปลี่ยนครั้งแรกจะทำให้ช่วงก่อนหน้าหายไป (ใบลาเก่าไม่มีผู้ลงนาม)
  insert into "AdminPositionHistory" (id_school, id_user, id_adminrole, start_date, note)
  select tt.id_school, tt.id_user, tt.id_adminrole, null, 'ตำแหน่งเดิมก่อนเริ่มบันทึกประวัติ'
  from "Teachers" tt
  join adminroles a on a."ID_AdminRoles" = tt.id_adminrole
  where tt.id_adminrole is not null
    and btrim(a."AdminRolesName") <> 'ไม่มีตำแหน่งบริหาร'
    and not exists (select 1 from "AdminPositionHistory" h where h.id_user = tt.id_user)
    and (tt.id_user = p_id_user
         or (p_replace and p_id_adminrole is not null and tt.id_adminrole = p_id_adminrole
             and tt.id_school = t.id_school));

  if exists (
    select 1 from "AdminPositionHistory" h
    where h.start_date > start_on
      and (h.id_user = p_id_user
           or (p_replace and h.id_adminrole = p_id_adminrole and h.id_school = t.id_school))
  ) then
    raise exception 'มีการเปลี่ยนตำแหน่งที่มีผลหลังวันที่ % บันทึกไว้แล้ว — ลบรายการนั้นก่อน', start_on;
  end if;

  -- ช่วงที่เริ่มวันเดียวกันพอดี = บันทึกซ้ำ/แก้ไขวันเดียวกัน → แทนที่
  delete from "AdminPositionHistory" h
  where h.start_date = start_on
    and (h.id_user = p_id_user
         or (p_replace and h.id_adminrole = p_id_adminrole and h.id_school = t.id_school));

  -- ปิดตำแหน่งเดิมของคนนี้
  update "AdminPositionHistory" h
  set end_date = start_on
  where h.id_user = p_id_user
    and (h.start_date is null or h.start_date < start_on)
    and (h.end_date is null or h.end_date > start_on);

  -- ปิดตำแหน่งของคนเดิมที่ถูกแทน
  if p_replace and p_id_adminrole is not null then
    for replaced in
      update "AdminPositionHistory" h
      set end_date = start_on
      where h.id_adminrole = p_id_adminrole
        and h.id_school = t.id_school
        and h.id_user <> p_id_user
        and (h.start_date is null or h.start_date < start_on)
        and (h.end_date is null or h.end_date > start_on)
      returning h.id_user
    loop
      perform public.sync_teacher_admin_role(replaced);
    end loop;
  end if;

  if p_id_adminrole is not null then
    insert into "AdminPositionHistory"
      (id_school, id_user, id_adminrole, start_date, note, created_by)
    values
      (t.id_school, p_id_user, p_id_adminrole, start_on, nullif(btrim(p_note), ''),
       public.current_teacher_id());
  end if;

  perform public.sync_teacher_admin_role(p_id_user);

  -- คนที่ไม่เคยมีประวัติและพ้นตำแหน่ง: sync ข้ามไปเพราะไม่มีแถว ต้องล้างเอง
  if p_id_adminrole is null and start_on <= public.today_th() then
    update "Teachers" set id_adminrole = null
    where id_user = p_id_user
      and not exists (select 1 from "AdminPositionHistory" h
                      where h.id_user = p_id_user
                        and (h.end_date is null or h.end_date > public.today_th()));
  end if;
end;
$$;

grant execute on function public.assign_admin_position(bigint, bigint, date, boolean, text)
  to authenticated;


-- ----------------------------------------------------------------------------
-- 5) ลบรายการที่บันทึกผิด — คืนช่วงเวลาให้รายการก่อนหน้าที่ถูกปิดเพราะรายการนี้
--    (บันทึก ผอ. คนใหม่ผิดคน → ลบ → ผอ. คนเดิมกลับมาดำรงตำแหน่งต่อ)
-- ----------------------------------------------------------------------------

create or replace function public.delete_admin_position(p_id_history bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  h        record;
  affected bigint;
begin
  select * into h from "AdminPositionHistory" where id_history = p_id_history;
  if not found then
    return;
  end if;

  if not public.can_manage_admin_positions(h.id_school) then
    raise exception 'ลบประวัติตำแหน่งบริหารได้เฉพาะผู้ดูแลระบบของโรงเรียนนี้';
  end if;

  delete from "AdminPositionHistory" where id_history = p_id_history;

  if h.start_date is not null then
    -- ต่อช่วงที่ถูกปิดตรงวันที่รายการนี้เริ่ม: ของคนเดิม (ตำแหน่งก่อนหน้า)
    -- และของคนที่ดำรงตำแหน่งเดียวกันอยู่ก่อน (คนที่ถูกแทน)
    for affected in
      update "AdminPositionHistory" p
      set end_date = h.end_date
      where p.end_date = h.start_date
        and (p.id_user = h.id_user
             or (p.id_adminrole = h.id_adminrole and p.id_school = h.id_school))
        and not exists (
          select 1 from "AdminPositionHistory" n
          where n.start_date = h.start_date
            and (n.id_user = p.id_user
                 or (n.id_adminrole = p.id_adminrole and n.id_school = p.id_school)))
      returning p.id_user
    loop
      perform public.sync_teacher_admin_role(affected);
    end loop;
  end if;

  perform public.sync_teacher_admin_role(h.id_user);

  -- ไม่เหลือประวัติเลย = ก่อนรายการนี้ไม่เคยมีตำแหน่ง (ตำแหน่งเดิมถูกเก็บเป็น
  -- ประวัติไว้ก่อนบันทึกเสมอ) — sync ข้ามคนที่ไม่มีประวัติ จึงต้องล้างเอง
  -- ไม่งั้นทะเบียนค้างตำแหน่งที่เพิ่งลบไป
  if not exists (select 1 from "AdminPositionHistory" x where x.id_user = h.id_user) then
    update "Teachers" set id_adminrole = null
    where id_user = h.id_user and id_adminrole is not null;
  end if;
end;
$$;

grant execute on function public.delete_admin_position(bigint) to authenticated;


-- ----------------------------------------------------------------------------
-- 6) เริ่มประวัติจากตำแหน่งปัจจุบัน — ทุกคนที่มีตำแหน่งบริหารอยู่วันนี้
--    = ดำรงตำแหน่งมาตั้งแต่ก่อนเริ่มบันทึก (start_date ว่าง)
--    รันซ้ำไม่เพิ่มแถวซ้ำ (เฉพาะคนที่ยังไม่มีประวัติเลย)
-- ----------------------------------------------------------------------------

insert into public."AdminPositionHistory" (id_school, id_user, id_adminrole, start_date, note)
select t.id_school, t.id_user, t.id_adminrole, null, 'ตำแหน่งเดิมก่อนเริ่มบันทึกประวัติ'
from public."Teachers" t
join public.adminroles a on a."ID_AdminRoles" = t.id_adminrole
where t.id_adminrole is not null
  and t.id_school is not null
  and btrim(a."AdminRolesName") <> 'ไม่มีตำแหน่งบริหาร'
  and not exists (select 1 from public."AdminPositionHistory" h where h.id_user = t.id_user);


notify pgrst, 'reload schema';


-- ----------------------------------------------------------------------------
-- 7) ตรวจผล — ทำเนียบตำแหน่งบริหารของแต่ละโรงเรียน
-- ----------------------------------------------------------------------------

select h.id_school                                   as โรงเรียน,
       a."AdminRolesName"                            as ตำแหน่ง,
       coalesce(to_jsonb(t) ->> 'fullName', '-')     as ชื่อ,
       coalesce(h.start_date::text, 'ก่อนเริ่มบันทึก') as ตั้งแต่,
       coalesce(h.end_date::text, 'ปัจจุบัน')         as ถึงก่อนวันที่
from public."AdminPositionHistory" h
left join public.adminroles a on a."ID_AdminRoles" = h.id_adminrole
left join public."Teachers" t on t.id_user = h.id_user
order by h.id_school, a."AdminRolesName", h.start_date nulls first;
