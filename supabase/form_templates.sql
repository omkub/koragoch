alter table public."FormTemplates" enable row level security;

do $$
declare
  p record;
begin
  for p in select policyname from pg_policies
           where schemaname = 'public' and tablename = 'FormTemplates'
  loop
    execute format('drop policy %I on public."FormTemplates"', p.policyname);
  end loop;
end $$;

create policy form_templates_select on "FormTemplates"
  for select to authenticated
  using (id_school is null or public.can_see_school(id_school));

create policy form_templates_insert on "FormTemplates"
  for insert to authenticated
  with check (public.is_super_admin());

create policy form_templates_delete on "FormTemplates"
  for delete to authenticated
  using (public.is_super_admin());

-- ไม่มี policy update — เวอร์ชันที่บันทึกแล้วแก้ไม่ได้


notify pgrst, 'reload schema';


-- ----------------------------------------------------------------------------
-- ตรวจผล — rowsecurity = true / policies = 3 / trigger = 1 / ฟังก์ชัน = 1
-- ----------------------------------------------------------------------------

select (select rowsecurity from pg_tables
         where schemaname = 'public' and tablename = 'FormTemplates')          as rowsecurity,
       (select count(*) from pg_policies
         where schemaname = 'public' and tablename = 'FormTemplates')          as policies,
       (select count(*) from pg_trigger
         where tgname = 'fill_form_template' and not tgisinternal)             as trigger,
       (select count(*) from pg_proc where proname = 'current_form_template')  as ฟังก์ชัน,
       (select count(*) from public."FormTemplates")                           as แม่แบบที่บันทึกไว้;
