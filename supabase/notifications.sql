--
--  หลักการ:
--    - ฐานข้อมูลสร้างแจ้งเตือนเอง (trigger บน Leaves) — ไม่ว่าใบลาจะมาจาก
--      app บนคอมพิวเตอร์ มือถือ หรือแอดมินส่งแทน ก็แจ้งเหมือนกัน
--      และครูปลอมแจ้งเตือนส่งให้แอดมินไม่ได้ (ไม่มี policy insert)
--    - 1 แถวต่อผู้รับ 1 คน — แต่ละแอดมินอ่าน/ลบของตัวเองได้อิสระ
