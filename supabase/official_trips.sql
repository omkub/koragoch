notify pgrst, 'reload schema';


-- ----------------------------------------------------------------------------
-- 8) ตรวจผล
--    ทั้งสองตารางต้อง rowsecurity = true
--    policy: OfficialTrips 4 / OfficialTripMembers 2
--    trigger: OfficialTrips 3 / OfficialTripMembers 1
-- ----------------------------------------------------------------------------

select c.tablename,
       c.rowsecurity,
       (select count(*) from pg_policies p
         where p.schemaname = 'public' and p.tablename = c.tablename) as policies,
       (select count(*) from pg_trigger g
         where g.tgrelid = format('public.%I', c.tablename)::regclass
           and not g.tgisinternal)                                      as triggers
from pg_tables c
where c.schemaname = 'public'
  and c.tablename in ('OfficialTrips', 'OfficialTripMembers')
order by c.tablename;
