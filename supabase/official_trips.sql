--  แนวคิด:
--    OfficialTrips        1 แถว = ไปราชการ 1 เรื่อง (ประชุม/อบรม/สัมมนา)
--                         id_user = ผู้บันทึกคำขอ (หัวหน้าคณะ)
--    OfficialTripMembers  รายชื่อทุกคนที่ไป รวมผู้บันทึกเอง (เพิ่มให้อัตโนมัติ)
--                         ใช้ตอบคำถาม "วันนี้ใครไปราชการ" และนับลงรายงาน
--
--  ไปราชการ "ไม่นับเป็นวันลา" — แยกตารางจาก Leaves โดยตั้งใจ
--
--  สิทธิ์ (เหมือนใบลา):
--    ครู/ผู้บริหาร   เห็นของทั้งโรงเรียน, บันทึก/แก้/ลบของตัวเองได้เฉพาะ
--                   ที่ยังรอพิจารณา, อนุมัติเองไม่ได้
--                   หลังอนุมัติแล้ว แก้ได้เฉพาะช่องรายงานผล + ไฟล์แนบ
--    ผู้ดูแลระบบ (22) ทำได้ทุกอย่างในโรงเรียนตัวเอง
--    ผู้ดูแลส่วนกลาง ทำได้ทุกโรงเรียน
--
--  ย้อนกลับ (ลบทิ้งทั้งหมด รวมข้อมูล):
--    drop table if exists public."OfficialTripMembers", public."OfficialTrips";
