-- ============================================================================
--  แจ้งเตือนแบบแอปจริง (Web Push) — เด้งที่มือถือ / คอม แม้ปิดแอปอยู่
--  เฉพาะผู้ดูแลระบบ (id_role 22) และผู้ดูแลส่วนกลาง
--
--  วิธีรัน: Supabase Dashboard > SQL Editor > วางทั้งไฟล์ > Run
--  รันซ้ำได้ ไม่พัง
--  ต้องรันก่อนแล้ว: notifications.sql, settings_secrets.sql (AppSecrets),
--                  staff_status.sql
--  ต้อง deploy ก่อน: Edge Function push-notify (ดู supabase/functions/README.md)
--
--  การทำงาน:
--    ใบลาใหม่ → notify_new_leave() สร้างแถว AppNotifications (กระดิ่งในแอป)
--    → trigger ในไฟล์นี้เรียก Edge Function push-notify (ผ่าน pg_net)
--    → ส่ง Web Push ไปทุกเครื่องที่ผู้รับเปิดแจ้งเตือนไว้ (ตาราง PushSubscriptions)
--
--  เปลี่ยนจากเดิม: ผู้ดูแลส่วนกลางได้แจ้งเตือนใบลาใหม่ของ "ทุกโรงเรียน"
--  (เดิมได้เฉพาะโรงเรียนที่ตัวเองสังกัด) และไม่แจ้งคนที่พ้นสภาพแล้ว
--
--  ปิดการเด้ง (กระดิ่งในแอปยังทำงาน):
--    drop trigger if exists push_new_notification on public."AppNotifications";
-- ============================================================================

create extension if not exists pg_net;


-- ----------------------------------------------------------------------------
-- 1) เครื่องที่เปิดรับแจ้งเตือน (1 แถวต่อ 1 เบราว์เซอร์/แอปที่ติดตั้ง)
-- ----------------------------------------------------------------------------

create table if not exists public."PushSubscriptions" (
  id_subscription  bigint generated by default as identity primary key,
  id_user          bigint not null references public."Teachers"(id_user) on delete cascade,
  endpoint         text   not null unique,
  p256dh           text   not null,
  auth             text   not null,
  user_agent       text,
  "createdAt"      timestamptz not null default now()
);

create index if not exists "PushSubscriptions_user_idx"
  on public."PushSubscriptions" (id_user);

alter table public."PushSubscriptions" enable row level security;

do $$
declare p record;
begin
  for p in select policyname from pg_policies
           where schemaname = 'public' and tablename = 'PushSubscriptions'
  loop
    execute format('drop policy %I on public."PushSubscriptions"', p.policyname);
  end loop;
end $$;

-- เห็น/ลบ ของตัวเอง · ลงทะเบียนได้เฉพาะผู้ดูแลระบบ (รวมส่วนกลาง)
create policy push_select on "PushSubscriptions"
  for select to authenticated
  using (id_user = public.current_teacher_id());

create policy push_insert on "PushSubscriptions"
  for insert to authenticated
  with check (id_user = public.current_teacher_id() and public.is_admin());

create policy push_update on "PushSubscriptions"
  for update to authenticated
  using (id_user = public.current_teacher_id())
  with check (id_user = public.current_teacher_id() and public.is_admin());

create policy push_delete on "PushSubscriptions"
  for delete to authenticated
  using (id_user = public.current_teacher_id());

comment on table public."PushSubscriptions" is
  'เครื่องที่เปิดแจ้งเตือนแบบแอป (Web Push) — เฉพาะผู้ดูแลระบบ';


-- ----------------------------------------------------------------------------
-- 2) รหัสลับระหว่างฐานข้อมูล ↔ Edge Function (สร้างครั้งเดียว)
--    กุญแจ VAPID ฟังก์ชันสร้างเองครั้งแรกแล้วเก็บใน AppSecrets
-- ----------------------------------------------------------------------------

insert into public."AppSecrets"(key, value)
values ('push_secret', encode(extensions.gen_random_bytes(32), 'hex'))
on conflict (key) do nothing;


-- ----------------------------------------------------------------------------
-- 3) แจ้งเตือนใหม่ → เด้งที่เครื่อง (ถ้าผู้รับเปิดแจ้งเตือนไว้อย่างน้อย 1 เครื่อง)
--    เรียกแบบไม่รอผล — ส่งไม่สำเร็จ ใบลาและกระดิ่งยังทำงานปกติ
-- ----------------------------------------------------------------------------

create or replace function public.push_new_notification()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if not exists (select 1 from "PushSubscriptions" s where s.id_user = new.recipient_id) then
    return new;
  end if;
  perform net.http_post(
    url     := 'https://uziajblqlbrvqmxvizsi.supabase.co/functions/v1/push-notify',
    headers := jsonb_build_object(
                 'content-type', 'application/json',
                 'x-push-secret', (select value from "AppSecrets" where key = 'push_secret')),
    body    := jsonb_build_object('id', new.id_notification),
    timeout_milliseconds := 15000
  );
  return new;
exception when others then
  raise warning 'push_new_notification: %', sqlerrm;
  return new;
end;
$$;

drop trigger if exists push_new_notification on public."AppNotifications";
create trigger push_new_notification
  after insert on public."AppNotifications"
  for each row execute function public.push_new_notification();


-- ----------------------------------------------------------------------------
-- 4) ผู้รับแจ้งเตือนใบลาใหม่: ผู้ดูแลระบบของโรงเรียนนั้น + ผู้ดูแลส่วนกลาง
--    (เหมือน notifications.sql ทุกอย่าง ยกเว้นเงื่อนไขผู้รับท้ายฟังก์ชัน)
-- ----------------------------------------------------------------------------

create or replace function public.notify_new_leave()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  leave     jsonb := to_jsonb(new);
  owner     record;
  type_name text;
  start_d   date;
  end_d     date;
  days      text;
  when_text text;
  actor     bigint := public.current_teacher_id();
begin
  if leave ->> 'firebase_id' is not null then
    return new;
  end if;

  select id_user, id_school, coalesce(to_jsonb(t) ->> 'fullName', to_jsonb(t) ->> 'fullname', '-') as name
    into owner
  from "Teachers" t where t.id_user = new.id_user;
  if not found then
    return new;
  end if;

  select coalesce(to_jsonb(lt) ->> 'leaveName', to_jsonb(lt) ->> 'Value')
    into type_name
  from "LeaveTypes" lt
  where (to_jsonb(lt) ->> 'id_leaveType') = leave ->> 'id_leaveType'
  limit 1;

  start_d := nullif(leave ->> 'startDate', '')::date;
  end_d   := coalesce(nullif(leave ->> 'endDate', '')::date, start_d);
  days    := nullif(leave ->> 'totalDays', '');
  when_text := case
    when start_d is null then ''
    when end_d = start_d then public.thai_short_date(start_d)
    else public.thai_short_date(start_d) || ' – ' || public.thai_short_date(end_d)
  end;

  insert into "AppNotifications"
    (id_school, recipient_id, type, title, body, ref_table, ref_id, actor_id)
  select owner.id_school,
         a.id_user,
         'leave_new',
         owner.name || ' ยื่น' || coalesce(type_name, 'ใบลา'),
         concat_ws(' · ',
           nullif(when_text, ''),
           case when days is not null
                then trim_scale(days::numeric)::text || ' วัน' end,
           nullif(leave ->> 'reason', '')),
         'Leaves',
         (leave ->> 'id_leaves')::bigint,
         actor
  from "Teachers" a
  where a.id_role = 22
    and a.employment_status = 'active'
    and (a.id_school = owner.id_school or a.is_super_admin)
    and a.id_user <> owner.id_user
    and a.id_user is distinct from actor;

  return new;
exception when others then
  raise warning 'notify_new_leave: %', sqlerrm;
  return new;
end;
$$;


notify pgrst, 'reload schema';


-- ----------------------------------------------------------------------------
-- 5) ตรวจผล — rls = true / policies = 4 / trigger = 1 / มีรหัสลับ = true
--    ดูผลการส่งล่าสุด:
--      select status_code, content, created
--      from net._http_response order by created desc limit 5;
-- ----------------------------------------------------------------------------

select (select rowsecurity from pg_tables
         where schemaname = 'public' and tablename = 'PushSubscriptions')   as rls,
       (select count(*) from pg_policies
         where schemaname = 'public' and tablename = 'PushSubscriptions')   as policies,
       (select count(*) from pg_trigger
         where tgname = 'push_new_notification' and not tgisinternal)       as trigger_push,
       exists (select 1 from public."AppSecrets" where key = 'push_secret') as มีรหัสลับ;
