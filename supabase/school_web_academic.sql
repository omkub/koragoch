-- ----------------------------------------------------------------------------
-- 1) ห้องเรียนและครูที่ปรึกษา (SchoolWebClassrooms)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebClassrooms" (
  id                  bigint generated by default as identity primary key,
  id_school           bigint not null references public."Schools"(id_school) on delete cascade,
  academic_year_id    bigint references public."AcademicYears"(id) on delete set null,
  grade_level         text not null,         -- เช่น 'ม.1', 'ป.6'
  room_no             text not null,         -- เช่น '1', '2'
  name                text not null,         -- เช่น 'ม.1/1'
  advisor_teacher_id  bigint,                -- อ้างอิง Teachers.id_user
  is_active           boolean not null default true,
  created_at          timestamptz not null default now()
);

create index if not exists "SchoolWebClassrooms_school_idx"
  on public."SchoolWebClassrooms" (id_school, is_active);

-- ----------------------------------------------------------------------------
-- 2) ทะเบียนนักเรียน (SchoolWebStudents)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebStudents" (
  id              bigint generated by default as identity primary key,
  id_school       bigint not null references public."Schools"(id_school) on delete cascade,
  student_code    text not null,
  prefix          text,                      -- เช่น 'เด็กชาย', 'เด็กหญิง', 'นาย', 'นางสาว'
  first_name      text not null,
  last_name       text not null,
  classroom_id    bigint references public."SchoolWebClassrooms"(id) on delete set null,
  guardian_name   text,
  guardian_phone  text,
  status          text not null default 'enrolled', -- 'enrolled' | 'transferred' | 'graduated' | 'dropped'
  created_at      timestamptz not null default now(),
  unique (id_school, student_code)
);

create index if not exists "SchoolWebStudents_school_idx"
  on public."SchoolWebStudents" (id_school, classroom_id, status);

-- ----------------------------------------------------------------------------
-- 3) รายวิชา (SchoolWebSubjects)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebSubjects" (
  id             bigint generated by default as identity primary key,
  id_school      bigint not null references public."Schools"(id_school) on delete cascade,
  code           text not null,              -- เช่น 'ว21101'
  name           text not null,              -- เช่น 'วิทยาศาสตร์ 1'
  department_id  bigint references public."SchoolDepartments"(id) on delete set null,
  credits        numeric(3,1) not null default 1.0,
  is_active      boolean not null default true,
  created_at     timestamptz not null default now(),
  unique (id_school, code)
);

create index if not exists "SchoolWebSubjects_school_idx"
  on public."SchoolWebSubjects" (id_school, is_active);

-- ----------------------------------------------------------------------------
-- 4) ตารางสอน (SchoolWebTeachingSchedules)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebTeachingSchedules" (
  id                bigint generated by default as identity primary key,
  id_school         bigint not null references public."Schools"(id_school) on delete cascade,
  academic_term_id  bigint references public."AcademicTerms"(id) on delete set null,
  classroom_id      bigint not null references public."SchoolWebClassrooms"(id) on delete cascade,
  subject_id        bigint not null references public."SchoolWebSubjects"(id) on delete cascade,
  teacher_id        bigint,                  -- อ้างอิง Teachers.id_user
  day_of_week       smallint not null check (day_of_week between 1 and 7), -- 1=จันทร์ .. 5=ศุกร์
  period_no         smallint not null check (period_no between 1 and 12),
  room_name         text,
  created_at        timestamptz not null default now()
);

create index if not exists "SchoolWebTeachingSchedules_school_idx"
  on public."SchoolWebTeachingSchedules" (id_school, classroom_id, day_of_week, period_no);

-- ----------------------------------------------------------------------------
-- 5) Row Level Security (RLS)
-- ----------------------------------------------------------------------------
alter table public."SchoolWebClassrooms" enable row level security;
alter table public."SchoolWebStudents" enable row level security;
alter table public."SchoolWebSubjects" enable row level security;
alter table public."SchoolWebTeachingSchedules" enable row level security;

-- SchoolWebClassrooms
drop policy if exists "school_web_classrooms_select" on public."SchoolWebClassrooms";
create policy "school_web_classrooms_select"
  on public."SchoolWebClassrooms" for select to authenticated
  using (public.can_see_school(id_school));

drop policy if exists "school_web_classrooms_write" on public."SchoolWebClassrooms";
create policy "school_web_classrooms_write"
  on public."SchoolWebClassrooms" for all to authenticated
  using (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()))
  with check (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()));

