-- ----------------------------------------------------------------------------
-- 1) ทะเบียนหนังสือราชการ / สารบรรณอิเล็กทรอนิกส์ (SchoolWebDocuments)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebDocuments" (
  id                  bigint generated by default as identity primary key,
  id_school           bigint not null references public."Schools"(id_school) on delete cascade,
  doc_no              text not null,         -- เช่น 'ศธ 04255/123'
  doc_type            text not null default 'incoming', -- 'incoming' | 'outgoing' | 'memo'
  title               text not null,
  sender_or_receiver  text,                  -- หน่วยงานต้นทาง / ปลายทาง
  doc_date            date not null default current_date,
  department_id       bigint references public."SchoolDepartments"(id) on delete set null,
  status              text not null default 'pending',  -- 'pending' | 'acknowledged' | 'archived'
  external_url        text,                  -- ลิงก์ไฟล์เอกสาร (เช่น Google Drive)
  created_at          timestamptz not null default now()
);

create index if not exists "SchoolWebDocuments_school_idx"
  on public."SchoolWebDocuments" (id_school, doc_date desc);

-- ----------------------------------------------------------------------------
-- 2) ประกาศข่าวสารโรงเรียน (SchoolWebAnnouncements)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebAnnouncements" (
  id            bigint generated by default as identity primary key,
  id_school     bigint not null references public."Schools"(id_school) on delete cascade,
  title         text not null,
  content       text,
  category      text not null default 'general', -- 'general' | 'academic' | 'hr'
  is_pinned     boolean not null default false,
  published_at  timestamptz not null default now(),
  created_at    timestamptz not null default now()
);

create index if not exists "SchoolWebAnnouncements_school_idx"
  on public."SchoolWebAnnouncements" (id_school, is_pinned desc, published_at desc);

-- ----------------------------------------------------------------------------
-- 3) Row Level Security (RLS)
-- ----------------------------------------------------------------------------
alter table public."SchoolWebDocuments" enable row level security;
alter table public."SchoolWebAnnouncements" enable row level security;

-- SchoolWebDocuments
drop policy if exists "school_web_documents_select" on public."SchoolWebDocuments";
create policy "school_web_documents_select"
  on public."SchoolWebDocuments" for select to authenticated
  using (public.can_see_school(id_school));

drop policy if exists "school_web_documents_write" on public."SchoolWebDocuments";
create policy "school_web_documents_write"
  on public."SchoolWebDocuments" for all to authenticated
  using (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()))
  with check (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()));

-- SchoolWebAnnouncements
drop policy if exists "school_web_announcements_select" on public."SchoolWebAnnouncements";
create policy "school_web_announcements_select"
  on public."SchoolWebAnnouncements" for select to authenticated
  using (public.can_see_school(id_school));

drop policy if exists "school_web_announcements_write" on public."SchoolWebAnnouncements";
create policy "school_web_announcements_write"
  on public."SchoolWebAnnouncements" for all to authenticated
  using (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()))
  with check (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()));
