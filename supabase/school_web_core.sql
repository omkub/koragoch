--
--  หมายเหตุ:
--    - ไฟล์นี้ "เพิ่มเฉพาะตารางใหม่" สำหรับ Web โรงเรียนเท่านั้น
--    - ไม่มีการแก้ไขหรือลบตาราง/ฟังก์ชันเดิมของระบบวันลาแม้แต่จุดเดียว
--    - รันซ้ำได้ปลอดภัย (Idempotent) ใน Supabase SQL Editor
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) ปีการศึกษา (AcademicYears)
-- ----------------------------------------------------------------------------
create table if not exists public."AcademicYears" (
  id          bigint generated by default as identity primary key,
  id_school   bigint not null references public."Schools"(id_school) on delete cascade,
  year_be     integer not null,          -- เช่น 2569
  label       text not null,             -- เช่น 'ปีการศึกษา 2569'
  start_date  date,
  end_date    date,
  is_current  boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (id_school, year_be)
);

create index if not exists "AcademicYears_school_idx"
  on public."AcademicYears" (id_school, is_current);

-- ----------------------------------------------------------------------------
-- 2) ภาคเรียน (AcademicTerms)
-- ----------------------------------------------------------------------------
create table if not exists public."AcademicTerms" (
  id                bigint generated by default as identity primary key,
  id_school         bigint not null references public."Schools"(id_school) on delete cascade,
  academic_year_id  bigint not null references public."AcademicYears"(id) on delete cascade,
  term_no           smallint not null,   -- 1, 2, 3 (ฤดูร้อน)
  label             text not null,       -- เช่น 'ภาคเรียนที่ 1/2569'
  start_date        date,
  end_date          date,
  is_current        boolean not null default false,
  created_at        timestamptz not null default now(),
  unique (academic_year_id, term_no)
);

create index if not exists "AcademicTerms_school_idx"
  on public."AcademicTerms" (id_school, is_current);

-- ----------------------------------------------------------------------------
-- 3) โครงสร้างหน่วยงาน / ฝ่าย / กลุ่มสาระ (SchoolDepartments)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolDepartments" (
  id          bigint generated by default as identity primary key,
  id_school   bigint not null references public."Schools"(id_school) on delete cascade,
  code        text,
  name        text not null,             -- เช่น 'กลุ่มสาระการเรียนรู้วิทยาศาสตร์ฯ', 'ฝ่ายบริหารงานบุคคล'
  category    text not null default 'department', -- 'management' | 'academic' | 'support' | 'department'
  sort_order  integer not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

create index if not exists "SchoolDepartments_school_idx"
  on public."SchoolDepartments" (id_school, sort_order);

-- ----------------------------------------------------------------------------
-- 4) ทะเบียนลิงก์ระบบย่อย / โมดูลภายนอก (SchoolModules)
--    ใช้เก็บลิงก์ของ "ระบบวันลา" และระบบอื่น ๆ ที่เชื่อมจาก Web โรงเรียน
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolModules" (
  id           bigint generated by default as identity primary key,
  id_school    bigint not null references public."Schools"(id_school) on delete cascade,
  module_key   text not null,            -- เช่น 'leave-app', 'leave-central'
  title        text not null,            -- เช่น 'ระบบวันลาและไปราชการ'
  description  text,
  url          text not null,            -- URL ปลายทางของระบบย่อย
  open_mode    text not null default 'new_tab', -- 'new_tab' | 'same_tab'
  category     text not null default 'hr',      -- 'hr' | 'academic' | 'admin' | 'other'
  sort_order   integer not null default 0,
  is_enabled   boolean not null default true,
  created_at   timestamptz not null default now(),
  unique (id_school, module_key)
);

create index if not exists "SchoolModules_school_idx"
  on public."SchoolModules" (id_school, sort_order);

-- ----------------------------------------------------------------------------
-- 5) Row Level Security (RLS) — อ้างอิงฟังก์ชันสิทธิ์เดิมของระบบ
--    อ่านได้เฉพาะโรงเรียนตัวเอง (หรือ super_admin)
--    แก้ไขได้เฉพาะ admin ของโรงเรียนนั้น (หรือ super_admin)
-- ----------------------------------------------------------------------------
alter table public."AcademicYears" enable row level security;
alter table public."AcademicTerms" enable row level security;
alter table public."SchoolDepartments" enable row level security;
alter table public."SchoolModules" enable row level security;

-- AcademicYears
drop policy if exists "school_web_academic_years_select" on public."AcademicYears";
create policy "school_web_academic_years_select"
  on public."AcademicYears" for select to authenticated
  using (public.can_see_school(id_school));

drop policy if exists "school_web_academic_years_write" on public."AcademicYears";
create policy "school_web_academic_years_write"
  on public."AcademicYears" for all to authenticated
  using (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()))
  with check (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()));

