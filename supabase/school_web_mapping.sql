-- ============================================================================
--  School Web 3-Tier Mapping — Part 1: School -> Division -> Sub-Module
--
--  โครงสร้างความสัมพันธ์:
--    1. SchoolWebModuleCatalog   : ทะเบียน Module มาตรฐานของแพลตฟอร์ม
--    2. SchoolWebDivisions       : "ฝ่าย" ของแต่ละโรงเรียน (map กับ id_school)
--    3. SchoolWebDivisionModules : "Module ย่อย" ที่สังกัดแต่ละฝ่าย (map กับ division_id)
--
--  หมายเหตุ:
--    - ใช้ชื่อตารางขึ้นต้นด้วย SchoolWeb... เพื่อไม่ให้ชนกับตารางเดิม
--    - ไม่แก้ไขตารางของระบบวันลาเดิม
--    - รันซ้ำได้ปลอดภัย (Idempotent) ใน Supabase SQL Editor
-- ============================================================================

