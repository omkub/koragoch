-- ----------------------------------------------------------------------------
-- 2) ฝ่ายของแต่ละโรงเรียน (SchoolWebDivisions — map กับ id_school)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebDivisions" (
  id            bigint generated by default as identity primary key,
  id_school     bigint not null references public."Schools"(id_school) on delete cascade,
  division_key  text not null,                -- 'hr' | 'academic' | 'admin' | 'finance' | custom
  name          text not null,                -- เช่น 'ฝ่ายบริหารงานบุคคล'
  description   text,
  icon_name     text not null default 'folder', -- 'users' | 'graduation-cap' | 'file-text' | 'wallet' | 'folder'
  sort_order    integer not null default 0,
  is_enabled    boolean not null default true,
  created_at    timestamptz not null default now(),
  unique (id_school, division_key)
);

create index if not exists "SchoolWebDivisions_school_idx"
  on public."SchoolWebDivisions" (id_school, sort_order);

-- ----------------------------------------------------------------------------
-- 3) Module ย่อยในแต่ละฝ่าย (SchoolWebDivisionModules — map กับ division_id)
-- ----------------------------------------------------------------------------
create table if not exists public."SchoolWebDivisionModules" (
  id                  bigint generated by default as identity primary key,
  id_school           bigint not null references public."Schools"(id_school) on delete cascade,
  division_id         bigint not null references public."SchoolWebDivisions"(id) on delete cascade,
  module_key          text not null,          -- อ้างอิง SchoolWebModuleCatalog หรือคีย์ของ Web ย่อยใหม่
  custom_title        text,
  custom_description  text,
  external_url        text,                   -- ลิงก์ Web ย่อยของฝ่ายนั้น
  open_mode           text not null default 'new_tab', -- 'new_tab' | 'same_tab'
  sort_order          integer not null default 0,
  is_enabled          boolean not null default true,
  created_at          timestamptz not null default now(),
  unique (division_id, module_key)
);

create index if not exists "SchoolWebDivisionModules_school_idx"
  on public."SchoolWebDivisionModules" (id_school, division_id, sort_order);

-- ----------------------------------------------------------------------------
-- 4) ฟังก์ชันตั้งค่าฝ่ายและ Module มาตรฐานให้โรงเรียน (เรียกซ้ำได้ปลอดภัย)
-- ----------------------------------------------------------------------------
create or replace function public.seed_school_web_divisions(target_school_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_div_hr       bigint;
  v_div_academic bigint;
  v_div_admin    bigint;
  v_div_finance  bigint;
begin
  if target_school_id is null then
    return;
  end if;

  -- สร้าง 4 ฝ่ายมาตรฐาน (ถ้ายังไม่มี)
  insert into public."SchoolWebDivisions" (id_school, division_key, name, description, icon_name, sort_order, is_enabled)
  values
    (target_school_id, 'hr',       'ฝ่ายบริหารงานบุคคล',       'งานวันลา ไปราชการ ทะเบียนบุคลากร และโครงสร้างหน่วยงาน', 'users',          1, true),
    (target_school_id, 'academic', 'ฝ่ายวิชาการและกิจการนักเรียน', 'งานทะเบียนนักเรียน ห้องเรียน หลักสูตร และตารางสอน',   'graduation-cap', 2, true),
    (target_school_id, 'admin',    'ฝ่ายบริหารทั่วไป',         'งานสารบรรณอิเล็กทรอนิกส์ และประกาศประชาสัมพันธ์',     'file-text',      3, true),
    (target_school_id, 'finance',  'ฝ่ายการเงินและพัสดุ',       'งานงบประมาณ การเงิน และพัสดุครุภัณฑ์',              'wallet',         4, true)
  on conflict (id_school, division_key) do nothing;

  select id into v_div_hr       from public."SchoolWebDivisions" where id_school = target_school_id and division_key = 'hr';
  select id into v_div_academic from public."SchoolWebDivisions" where id_school = target_school_id and division_key = 'academic';
  select id into v_div_admin    from public."SchoolWebDivisions" where id_school = target_school_id and division_key = 'admin';
  select id into v_div_finance  from public."SchoolWebDivisions" where id_school = target_school_id and division_key = 'finance';

  -- ผูก Module ย่อยเริ่มต้นเข้ากับแต่ละฝ่าย (ถ้ายังไม่มี)
  if v_div_hr is not null then
    insert into public."SchoolWebDivisionModules" (id_school, division_id, module_key, external_url, sort_order, is_enabled)
    values
      (target_school_id, v_div_hr, 'leave-system',   'https://rbp-chanikarnn.web.app/', 1, true),
      (target_school_id, v_div_hr, 'staff-registry', null,                              2, true),
      (target_school_id, v_div_hr, 'departments',    null,                              3, true)
    on conflict (division_id, module_key) do nothing;
  end if;

  if v_div_academic is not null then
    insert into public."SchoolWebDivisionModules" (id_school, division_id, module_key, sort_order, is_enabled)
    values
      (target_school_id, v_div_academic, 'students-classrooms', 1, true),
      (target_school_id, v_div_academic, 'curriculum-schedule', 2, true)
    on conflict (division_id, module_key) do nothing;
  end if;

  if v_div_admin is not null then
    insert into public."SchoolWebDivisionModules" (id_school, division_id, module_key, sort_order, is_enabled)
    values
      (target_school_id, v_div_admin, 'documents',     1, true),
      (target_school_id, v_div_admin, 'announcements', 2, true)
    on conflict (division_id, module_key) do nothing;
  end if;

  if v_div_finance is not null then
    insert into public."SchoolWebDivisionModules" (id_school, division_id, module_key, sort_order, is_enabled)
    values
      (target_school_id, v_div_finance, 'finance-budget', 1, true)
    on conflict (division_id, module_key) do nothing;
  end if;
end;
$$;

grant execute on function public.seed_school_web_divisions(bigint) to authenticated;

-- เตรียมข้อมูลเริ่มต้นให้ทุกโรงเรียนที่มีอยู่ในระบบปัจจุบันทันที
do $$
declare
  r record;
begin
  for r in select id_school from public."Schools" loop
    perform public.seed_school_web_divisions(r.id_school);
  end loop;
end;
$$;

-- ----------------------------------------------------------------------------
-- 5) Row Level Security (RLS)
-- ----------------------------------------------------------------------------
alter table public."SchoolWebModuleCatalog" enable row level security;
alter table public."SchoolWebDivisions" enable row level security;
alter table public."SchoolWebDivisionModules" enable row level security;

-- SchoolWebModuleCatalog: ทุกคนที่ล็อกอินอ่านได้, แก้ไขได้เฉพาะ super_admin
drop policy if exists "school_web_catalog_select" on public."SchoolWebModuleCatalog";
create policy "school_web_catalog_select"
  on public."SchoolWebModuleCatalog" for select to authenticated
  using (true);

drop policy if exists "school_web_catalog_write" on public."SchoolWebModuleCatalog";
create policy "school_web_catalog_write"
  on public."SchoolWebModuleCatalog" for all to authenticated
  using (public.is_super_admin())
  with check (public.is_super_admin());

-- SchoolWebDivisions
drop policy if exists "school_web_divisions_select" on public."SchoolWebDivisions";
create policy "school_web_divisions_select"
  on public."SchoolWebDivisions" for select to authenticated
  using (public.can_see_school(id_school));

drop policy if exists "school_web_divisions_write" on public."SchoolWebDivisions";
create policy "school_web_divisions_write"
  on public."SchoolWebDivisions" for all to authenticated
  using (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()))
  with check (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()));

-- SchoolWebDivisionModules
drop policy if exists "school_web_div_modules_select" on public."SchoolWebDivisionModules";
create policy "school_web_div_modules_select"
  on public."SchoolWebDivisionModules" for select to authenticated
  using (public.can_see_school(id_school));

drop policy if exists "school_web_div_modules_write" on public."SchoolWebDivisionModules";
create policy "school_web_div_modules_write"
  on public."SchoolWebDivisionModules" for all to authenticated
  using (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()))
  with check (public.is_super_admin() or (public.is_admin() and id_school = public.current_school_id()));
